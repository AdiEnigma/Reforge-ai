# Primary Validation Function
# ---------------------------------------------------------------------------

def validate_cad_geometry(
    workplane: Any,
    cad_spec: Union[Any, Dict[str, Any]],
    feature_tree: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Validates generated 3D CAD geometry against specification.

    Args:
        workplane: Generated CadQuery Workplane.
        cad_spec: CadSpec dataclass instance or normalized specification dict.
        feature_tree: Optional feature tree returned by generator.

    Returns:
        {
            "valid": bool,
            "fit_score": float,
            "issues": List[str],
            "metrics": Dict[str, Any],
        }
    """
    issues: List[str] = []
    metrics: Dict[str, Any] = {
        "style": None,
        "solid_count": 0,
        "actual_volume_mm3": 0.0,
        "actual_bbox": {},
        "expected_bbox": {},
        "bbox_relative_errors": {},
        "bbox_valid": False,
        "geometry_valid": False,
        "volume_estimate_mm3": None,
        "volume_relative_error": None,
        "volume_component_available": False,
        "feature_checks": {},
        "fit_score_method": "none",
    }

    # Extract spec dictionary
    if hasattr(cad_spec, "spec") and isinstance(cad_spec.spec, dict):
        spec = cad_spec.spec
        # Check if Step 1 marked it rejected
        if hasattr(cad_spec, "status") and cad_spec.status == "rejected":
            issues.append("Input CadSpec has status 'rejected'.")
    elif isinstance(cad_spec, dict):
        spec = cad_spec.get("spec", cad_spec)
    else:
        issues.append(f"Invalid cad_spec type: {type(cad_spec).__name__}.")
        return {"valid": False, "fit_score": 0.0, "issues": issues, "metrics": metrics}

    style = spec.get("style")
    metrics["style"] = style

    # 1. Basic CAD Integrity Checks
    if workplane is None or not isinstance(workplane, cq.Workplane):
        issues.append("Workplane is None or not a valid CadQuery Workplane.")
        return {"valid": False, "fit_score": 0.0, "issues": issues, "metrics": metrics}

    try:
        solids = workplane.solids().vals()
    except Exception as e:
        issues.append(f"Failed to retrieve solids from workplane: {str(e)}")
        return {"valid": False, "fit_score": 0.0, "issues": issues, "metrics": metrics}

    metrics["solid_count"] = len(solids)
    if len(solids) == 0:
        issues.append("Geometry contains 0 solids.")
        return {"valid": False, "fit_score": 0.0, "issues": issues, "metrics": metrics}

    if len(solids) != 1:
        issues.append(f"Expected exactly 1 solid, found {len(solids)} disconnected solids.")
        return {"valid": False, "fit_score": 0.0, "issues": issues, "metrics": metrics}

    solid = solids[0]

    # Check OCC validity
    try:
        is_shape_valid = solid.isValid()
    except Exception as e:
        is_shape_valid = False
        issues.append(f"OCC validity check raised exception: {str(e)}")

    if not is_shape_valid:
        issues.append("OpenCASCADE solid validity check (isValid) returned False.")

    # Check volume
    try:
        actual_vol = solid.Volume()
    except Exception as e:
        actual_vol = 0.0
        issues.append(f"Failed to calculate solid volume: {str(e)}")

    metrics["actual_volume_mm3"] = actual_vol
    if actual_vol <= 0 or math.isnan(actual_vol) or math.isinf(actual_vol):
        issues.append(f"Solid has non-positive or invalid volume: {actual_vol}")

    # Check bounding box
    try:
        bb = solid.BoundingBox()
        actual_bbox = {
            "xmin": bb.xmin, "xmax": bb.xmax, "xlen": bb.xlen,
            "ymin": bb.ymin, "ymax": bb.ymax, "ylen": bb.ylen,
            "zmin": bb.zmin, "zmax": bb.zmax, "zlen": bb.zlen,
        }
        metrics["actual_bbox"] = actual_bbox
        if bb.xlen <= 0 or bb.ylen <= 0 or bb.zlen <= 0:
            issues.append(f"Solid has degenerate bounding box: ({bb.xlen}, {bb.ylen}, {bb.zlen})")
    except Exception as e:
        actual_bbox = {}
        issues.append(f"Failed to calculate bounding box: {str(e)}")

    # Mark basic geometry validity
    geometry_valid = (
        is_shape_valid
        and len(solids) == 1
        and actual_vol > 0
        and actual_bbox.get("xlen", 0) > 0
        and actual_bbox.get("ylen", 0) > 0
        and actual_bbox.get("zlen", 0) > 0
    )
    metrics["geometry_valid"] = geometry_valid

    # 2. Bounding-Box Comparison
    expected_bbox, bbox_err = _calculate_expected_bbox(spec)
    metrics["expected_bbox"] = expected_bbox
    bbox_valid = False
    max_e_b = 0.0

    if expected_bbox:
        bbox_errors: Dict[str, float] = {}
        # Dimension relative errors
        for dim in ["xlen", "ylen", "zlen"]:
            exp_d = expected_bbox[dim]
            act_d = actual_bbox.get(dim, 0.0)
            if exp_d > 0:
                rel_err = abs(act_d - exp_d) / exp_d
                bbox_errors[dim] = rel_err
                max_e_b = max(max_e_b, rel_err)
                if rel_err > BBOX_RELATIVE_TOLERANCE:
                    issues.append(
                        f"Bounding box dimension '{dim}' ({act_d:.2f} mm) differs from expected "
                        f"({exp_d:.2f} mm) by {rel_err * 100:.2f}% (exceeds {BBOX_RELATIVE_TOLERANCE * 100:.0f}% tolerance)."
                    )

        # Coordinate absolute / normalized errors for bounds
        for coord in ["xmin", "xmax", "ymin", "ymax", "zmin", "zmax"]:
            exp_c = expected_bbox[coord]
            act_c = actual_bbox.get(coord, 0.0)
            coord_tol = max(1e-6, BBOX_RELATIVE_TOLERANCE * max(abs(exp_c), 1.0))
            if abs(act_c - exp_c) > coord_tol:
                issues.append(
                    f"Bounding box coordinate '{coord}' ({act_c:.2f} mm) differs from expected "
                    f"({exp_c:.2f} mm) by {abs(act_c - exp_c):.2f} mm."
                )

        metrics["bbox_relative_errors"] = bbox_errors
        bbox_valid = all(err <= BBOX_RELATIVE_TOLERANCE for err in bbox_errors.values()) and not any(
            "Bounding box" in iss for iss in issues
        )
    else:
        if bbox_err:
            issues.append(f"Expected bounding box unavailable: {bbox_err}")

    metrics["bbox_valid"] = bbox_valid

    # 3. Feature Consistency Validation
    feature_checks: Dict[str, Any] = {}
    if style == "extruded":
        expected_holes = spec.get("holes", [])
        actual_holes = _inspect_extruded_holes(solid)
        feature_checks["expected_hole_count"] = len(expected_holes)
        feature_checks["actual_hole_count"] = len(actual_holes)
        if len(expected_holes) > 0:
            if len(actual_holes) != len(expected_holes):
                issues.append(
                    f"Extruded hole count mismatch: expected {len(expected_holes)}, detected {len(actual_holes)}."
                )
            else:
                # Check diameters
                for i, eh in enumerate(expected_holes):
                    exp_dia = float(eh["radius"]) * 2.0
                    match = any(abs(ah["diameter"] - exp_dia) / exp_dia < 0.02 for ah in actual_holes)
                    if not match:
                        issues.append(f"Expected hole {i} diameter ({exp_dia:.2f} mm) not detected in geometry.")

    elif style == "gear":
        gear_spec = spec.get("gear", {})
        exp_teeth = gear_spec.get("teeth")
        exp_bore_r = gear_spec.get("boreRadius", 0.0)
        feature_checks["expected_teeth"] = exp_teeth
        feature_checks["expected_bore_diameter"] = 2.0 * exp_bore_r if exp_bore_r > 0 else 0.0

        # Bore verification
        actual_bore_d = _inspect_gear_bore(solid)
        feature_checks["actual_bore_diameter"] = actual_bore_d
        if exp_bore_r > 0:
            exp_bore_d = 2.0 * exp_bore_r
            if actual_bore_d is None:
                issues.append(f"Expected gear bore of diameter {exp_bore_d:.2f} mm was not found in geometry.")
            elif abs(actual_bore_d - exp_bore_d) / exp_bore_d > 0.02:
                issues.append(
                    f"Gear bore diameter mismatch: expected {exp_bore_d:.2f} mm, found {actual_bore_d:.2f} mm."
                )
        else:
            if actual_bore_d is not None:
                issues.append(f"Unexpected bore detected in gear geometry: {actual_bore_d:.2f} mm.")

        # Tooth count verification
        # In cq_gears, each tooth produces 4 perimeter boundary faces (2 flanks + tip + root)
        # plus top & bottom faces (+ central bore if present).
        # We perform topological boundary check and cross-reference with feature_tree
        bspline_faces = [f for f in solid.Faces() if f.geomType() == "BSPLINE"]
        feature_checks["bspline_tooth_faces"] = len(bspline_faces)
        if exp_teeth:
            # If feature tree is supplied, check consistency
            if feature_tree and feature_tree.get("parameters", {}).get("teeth") != exp_teeth:
                issues.append("Feature tree tooth count differs from CadSpec specification.")

    elif style == "combination":
        feature_checks["single_fused_solid"] = (len(solids) == 1)

    elif style == "revolved":
        feature_checks["rotational_solid_valid"] = geometry_valid

    metrics["feature_checks"] = feature_checks

    # 4. Backend Volume Cross-Check
    est_vol_mm3, vol_source, vol_err = _invoke_backend_volume_estimator(spec)
    metrics["volume_estimate_mm3"] = est_vol_mm3
    vol_comp_available = False
    e_v = 0.0

    if est_vol_mm3 is not None and est_vol_mm3 > 0:
        vol_comp_available = True
        metrics["volume_component_available"] = True
        vol_rel_err = abs(actual_vol - est_vol_mm3) / est_vol_mm3
        metrics["volume_relative_error"] = vol_rel_err
        e_v = vol_rel_err

        diag_thresh = VOLUME_DIAGNOSTIC_THRESHOLDS.get(style)
        if diag_thresh is not None and vol_rel_err > diag_thresh:
            issues.append(
                f"Diagnostic volume discrepancy: actual CAD volume ({actual_vol:.2f} mm³) differs "
                f"from backend estimate ({est_vol_mm3:.2f} mm³, source: {vol_source}) by {vol_rel_err * 100:.2f}% "
                f"(threshold: {diag_thresh * 100:.0f}%)."
            )
    else:
        metrics["volume_component_available"] = False
        if vol_err:
            issues.append(f"Backend volume estimator unavailable: {vol_err}")

    # 5. Fit Score Calculation
    # Formula: fit_score = max(0.0, 1.0 - max(E_V, E_B))
    if not geometry_valid:
        fit_score = 0.0
        metrics["fit_score_method"] = "zero_invalid_geometry"
    elif not bbox_valid:
        fit_score = 0.0
        metrics["fit_score_method"] = "zero_invalid_bbox"
    else:
        if vol_comp_available:
            error_term = max(e_v, max_e_b)
            metrics["fit_score_method"] = "volume_and_bbox"
        else:
            error_term = max_e_b
            metrics["fit_score_method"] = "bbox_only"

        fit_score = max(0.0, min(1.0, 1.0 - error_term))

    # Final overall validity: True iff mandatory CAD geometry checks pass
    # (backend volume disagreement does NOT set valid=False per Section 7)
    fatal_issues = [
        iss for iss in issues
        if not iss.startswith("Diagnostic volume discrepancy")
        and not iss.startswith("Backend volume estimator unavailable")
    ]
    valid = geometry_valid and bbox_valid and len(fatal_issues) == 0

    return {
        "valid": valid,
        "fit_score": round(fit_score, 4),
        "issues": issues,
        "metrics": metrics,
    }

