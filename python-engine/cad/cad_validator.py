"""
cad_validator.py — Independent CAD Geometry Validation Layer for ReForge AI.

Step 4 of the ReForge AI CAD pipeline.
Validates 3D CAD geometry generated by Steps 1–3:
- Checks basic CAD integrity (single solid, validity, finite positive volume, non-degenerate bbox).
- Validates bounding-box dimensions against CadSpec with 1% relative tolerance.
- Cross-checks solid volume against backend geometry-volume.js estimator (diagnostic).
- Performs feature consistency checks:
  - Extruded: hole count, positions, and diameters (via topological cylindrical face inspection).
  - Gear: face width, bore diameter (via topological cylindrical bore inspection), and tooth count.
  - Revolved: profile extent and rotational symmetry.
  - Combination: single fused solid, positive volume.
- Computes mathematical fit score in [0.0, 1.0]:
    E_V = abs(V_actual - V_expected) / V_expected
    E_B = max(E_x, E_y, E_z)
    fit_score = max(0.0, 1.0 - max(E_V, E_B))
"""

from __future__ import annotations

import json
import logging
import math
import os
import subprocess
from typing import Any, Dict, List, Optional, Tuple, Union

import cadquery as cq

logger = logging.getLogger("reforge.cad.cad_validator")

# Relative tolerance for positive bounding box dimensions
BBOX_RELATIVE_TOLERANCE = 0.01

# Diagnostic thresholds for backend volume comparison (does NOT invalidate geometry)
VOLUME_DIAGNOSTIC_THRESHOLDS = {
    "revolved": 0.01,    # 1%
    "extruded": 0.01,    # 1%
    "gear": 0.35,        # 35% (approximate cost-estimation analytical formula)
    "combination": None, # overlap not deducted in backend estimator
}


# ---------------------------------------------------------------------------
# Backend Volume Cross-Check Helper
# ---------------------------------------------------------------------------

def _invoke_backend_volume_estimator(geometry_recipe: Dict[str, Any]) -> Tuple[Optional[float], Optional[str], Optional[str]]:
    """
    Invokes backend/geometry-volume.js estimateVolumeCm3 via Node.js subprocess.
    Returns:
        (volume_mm3, source, error_or_none)
    """
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    estimator_path = os.path.join(repo_root, "backend", "geometry-volume.js")

    if not os.path.exists(estimator_path):
        return None, None, f"Estimator file not found at {estimator_path}"

    payload = json.dumps({"geometryRecipe": geometry_recipe})
    # Node script that requires/imports estimateVolumeCm3
    node_code = f"""
    try {{
        const path = require('path');
        const {{ estimateVolumeCm3 }} = require(path.resolve('{estimator_path}'));
        const analysis = {payload};
        const result = estimateVolumeCm3(analysis);
        console.log(JSON.stringify(result));
    }} catch (err) {{
        console.error(err.message);
        process.exit(1);
    }}
    """
    try:
        res = subprocess.run(["node", "-e", node_code], capture_output=True, text=True, timeout=5)
        if res.returncode != 0:
            return None, None, f"Node execution error: {res.stderr.strip()}"
        out = json.loads(res.stdout.strip())
        vol_cm3 = out.get("volumeCm3")
        source = out.get("source")
        if vol_cm3 is not None and isinstance(vol_cm3, (int, float)) and math.isfinite(vol_cm3) and vol_cm3 > 0:
            return vol_cm3 * 1000.0, source, None
        return None, source, f"Estimator returned invalid volume: {vol_cm3}"
    except Exception as e:
        return None, None, f"Failed to invoke backend volume estimator: {str(e)}"


# ---------------------------------------------------------------------------
# Expected Bounding-Box Calculation
# ---------------------------------------------------------------------------

def _calculate_expected_bbox(spec: Dict[str, Any]) -> Tuple[Optional[Dict[str, float]], Optional[str]]:
    """
    Calculates expected bounding box dimensions (xlen, ylen, zlen, xmin, xmax, ymin, ymax, zmin, zmax).
    Returns (expected_bbox, error_or_none).
    """
    style = spec.get("style")
    if not style:
        return None, "Missing component style in specification."

    if style == "extruded":
        outline = spec.get("outline", [])
        depth = spec.get("depth")
        if not outline or depth is None or depth <= 0:
            return None, "Invalid outline or depth for extruded style."
        xs = [float(pt["x"]) for pt in outline]
        ys = [float(pt["y"]) for pt in outline]
        xmin, xmax = min(xs), max(xs)
        ymin, ymax = min(ys), max(ys)
        zmin, zmax = 0.0, float(depth)
        return {
            "xmin": xmin, "xmax": xmax, "xlen": xmax - xmin,
            "ymin": ymin, "ymax": ymax, "ylen": ymax - ymin,
            "zmin": zmin, "zmax": zmax, "zlen": zmax - zmin,
        }, None

    elif style == "revolved":
        profile = spec.get("revolvedProfile", [])
        if not profile or len(profile) < 2:
            return None, "Invalid profile points for revolved style."
        zs = [float(pt["z"]) for pt in profile]
        rs = [float(pt["radius"]) for pt in profile]
        zmin, zmax = min(zs), max(zs)
        max_r = max(rs)
        return {
            "xmin": -max_r, "xmax": max_r, "xlen": 2.0 * max_r,
            "ymin": -max_r, "ymax": max_r, "ylen": 2.0 * max_r,
            "zmin": zmin, "zmax": zmax, "zlen": zmax - zmin,
        }, None

    elif style == "gear":
        gear = spec.get("gear", {})
        teeth = gear.get("teeth")
        module = gear.get("module")
        width = gear.get("faceWidth")
        if teeth is None or module is None or width is None:
            return None, "Missing teeth, module, or faceWidth for gear style."
        # Standard spur gear tip diameter D_o = (teeth + 2) * module
        tip_r = ((float(teeth) + 2.0) * float(module)) / 2.0
        return {
            "xmin": -tip_r, "xmax": tip_r, "xlen": 2.0 * tip_r,
            "ymin": -tip_r, "ymax": tip_r, "ylen": 2.0 * tip_r,
            "zmin": 0.0, "zmax": float(width), "zlen": float(width),
        }, None

    elif style == "combination":
        # Combination primitives can have arbitrary rotations & unions
        # Expected bbox is derived from primitive bounds if computable
        prims = spec.get("primitives", [])
        if not prims:
            return None, "Missing primitives for combination style."
        # Check if all primitives are unrotated boxes or axis-aligned
        min_x = min_y = min_z = float("inf")
        max_x = max_y = max_z = float("-inf")
        for p in prims:
            pos = p.get("position", {})
            rot = p.get("rotation", {})
            rx = float(rot.get("x", 0.0))
            ry = float(rot.get("y", 0.0))
            rz = float(rot.get("z", 0.0))
            px = float(pos.get("x", 0.0))
            py = float(pos.get("y", 0.0))
            pz = float(pos.get("z", 0.0))
            kind = p.get("kind")
            if rx == 0.0 and ry == 0.0 and rz == 0.0:
                if kind == "box":
                    hw = float(p.get("width", 10.0)) / 2.0
                    hh = float(p.get("height", 10.0)) / 2.0
                    hd = float(p.get("depth", 10.0)) / 2.0
                    min_x = min(min_x, px - hw); max_x = max(max_x, px + hw)
                    min_y = min(min_y, py - hh); max_y = max(max_y, py + hh)
                    min_z = min(min_z, pz - hd); max_z = max(max_z, pz + hd)
                elif kind == "cylinder":
                    r = float(p.get("radius", 5.0))
                    hh = float(p.get("height", 10.0)) / 2.0
                    min_x = min(min_x, px - r); max_x = max(max_x, px + r)
                    min_y = min(min_y, py - r); max_y = max(max_y, py + r)
                    min_z = min(min_z, pz - hh); max_z = max(max_z, pz + hh)
                elif kind == "sphere":
                    r = float(p.get("radius", 5.0))
                    min_x = min(min_x, px - r); max_x = max(max_x, px + r)
                    min_y = min(min_y, py - r); max_y = max(max_y, py + r)
                    min_z = min(min_z, pz - r); max_z = max(max_z, pz + r)
        if math.isfinite(min_x) and math.isfinite(max_x):
            return {
                "xmin": min_x, "xmax": max_x, "xlen": max_x - min_x,
                "ymin": min_y, "ymax": max_y, "ylen": max_y - min_y,
                "zmin": min_z, "zmax": max_z, "zlen": max_z - min_z,
            }, None
        return None, "Combination expected bounding box cannot be derived without simulation."

    return None, f"Unsupported style '{style}' for expected bounding box."


# ---------------------------------------------------------------------------
# Topological Feature Inspection Helpers
# ---------------------------------------------------------------------------

def _inspect_extruded_holes(solid: cq.Solid) -> List[Dict[str, float]]:
    """
    Inspects internal cylindrical faces oriented along Z to find through-holes.
    Returns list of hole info: [{'cx', 'cy', 'diameter', 'depth'}]
    """
    holes: List[Dict[str, float]] = []
    for f in solid.Faces():
        if f.geomType() == "CYLINDER":
            bb = f.BoundingBox()
            # Through-hole along Z should span the thickness
            # and have approximately equal xlen and ylen (circular)
            if abs(bb.xlen - bb.ylen) < 0.1 and bb.xlen > 0.01:
                cx = (bb.xmin + bb.xmax) / 2.0
                cy = (bb.ymin + bb.ymax) / 2.0
                diameter = (bb.xlen + bb.ylen) / 2.0
                holes.append({
                    "cx": cx,
                    "cy": cy,
                    "diameter": diameter,
                    "depth": bb.zlen,
                })
    return holes


def _inspect_gear_bore(solid: cq.Solid) -> Optional[float]:
    """
    Inspects central cylindrical face centered at origin (0, 0) to find gear bore diameter.
    """
    for f in solid.Faces():
        if f.geomType() == "CYLINDER":
            bb = f.BoundingBox()
            cx = (bb.xmin + bb.xmax) / 2.0
            cy = (bb.ymin + bb.ymax) / 2.0
            if math.sqrt(cx**2 + cy**2) < 0.2:
                # Centered at rotation origin
                return (bb.xlen + bb.ylen) / 2.0
    return None


