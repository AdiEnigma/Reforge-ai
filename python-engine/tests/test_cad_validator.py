def test_valid_extruded_solid():
    """Verify a valid extruded solid passes validation with high fit score."""
    recipe = {
        "style": "extruded",
        "outline": [
            {"x": 0.0, "y": 0.0},
            {"x": 30.0, "y": 0.0},
            {"x": 30.0, "y": 30.0},
            {"x": 0.0, "y": 30.0},
        ],
        "depth": 15.0,
    }
    cad_spec = validate_recipe(recipe)
    wp, ft = generate_cad(cad_spec)
    result = validate_cad_geometry(wp, cad_spec, ft)

    assert result["valid"] is True
    assert result["fit_score"] >= 0.99
    assert result["metrics"]["solid_count"] == 1
    assert result["metrics"]["geometry_valid"] is True
    assert result["metrics"]["bbox_valid"] is True
    assert len(result["issues"]) == 0


