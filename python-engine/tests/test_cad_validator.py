def test_none_or_empty_workplane_rejected():
    """Verify None or empty Workplane fails validation with fit_score=0."""
    recipe = {"style": "extruded", "outline": [{"x":0,"y":0},{"x":10,"y":0},{"x":10,"y":10},{"x":0,"y":10}], "depth": 5}
    cad_spec = validate_recipe(recipe)

    # 1. None
    res_none = validate_cad_geometry(None, cad_spec)
    assert res_none["valid"] is False
    assert res_none["fit_score"] == 0.0
    assert any("Workplane is None" in iss for iss in res_none["issues"])

    # 2. Empty workplane (no solids)
    empty_wp = cq.Workplane("XY")
    res_empty = validate_cad_geometry(empty_wp, cad_spec)
    assert res_empty["valid"] is False
    assert res_empty["fit_score"] == 0.0
    assert any("0 solids" in iss for iss in res_empty["issues"])


def test_multiple_disconnected_solids_rejected():
    """Verify geometry containing multiple disconnected solids fails validation."""
    recipe = {"style": "extruded", "outline": [{"x":0,"y":0},{"x":10,"y":0},{"x":10,"y":10},{"x":0,"y":10}], "depth": 5}
    cad_spec = validate_recipe(recipe)

    # Create two disconnected boxes
    b1 = cq.Workplane("XY").box(10, 10, 10)
    b2 = cq.Workplane("XY").box(10, 10, 10).translate((100, 100, 100))
    multi_wp = b1.add(b2)

    result = validate_cad_geometry(multi_wp, cad_spec)
    assert result["valid"] is False
    assert result["fit_score"] == 0.0
    assert any("disconnected solids" in iss for iss in result["issues"])


