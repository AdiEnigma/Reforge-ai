def test_fit_score_bounds_and_zero_on_invalid():
    """Verify fit score always lies in [0.0, 1.0] and is 0.0 on invalid geometry."""
    recipe = {"style": "extruded", "outline": [{"x":0,"y":0},{"x":10,"y":0},{"x":10,"y":10},{"x":0,"y":10}], "depth": 5}
    cad_spec = validate_recipe(recipe)

    # Degenerate workplane
    res = validate_cad_geometry(None, cad_spec)
    assert res["fit_score"] == 0.0

    # Valid geometry
    wp, ft = generate_cad(cad_spec)
    res_valid = validate_cad_geometry(wp, cad_spec, ft)
    assert 0.0 <= res_valid["fit_score"] <= 1.0


def test_rejected_cad_spec_handling():
    """Verify rejected CadSpec produces valid=False and reports issue."""
    rejected_spec = CadSpec(spec={"style": "extruded"}, status="rejected", errors=["Invalid polygon"])
    box_wp = cq.Workplane("XY").box(10, 10, 10)
    res = validate_cad_geometry(box_wp, rejected_spec)
    assert res["valid"] is False
    assert any("rejected" in iss for iss in res["issues"])

