def test_bounding_box_mismatch_detected():
    """Verify mismatched dimensions fail bounding box check and set valid=False."""
    recipe = {
        "style": "extruded",
        "outline": [
            {"x": 0.0, "y": 0.0},
            {"x": 20.0, "y": 0.0},
            {"x": 20.0, "y": 20.0},
            {"x": 0.0, "y": 20.0},
        ],
        "depth": 10.0,
    }
    cad_spec = validate_recipe(recipe)
    # Generate geometry with depth=50 instead of 10
    wrong_wp = cq.Workplane("XY").polyline([(0,0),(20,0),(20,20),(0,20)]).close().extrude(50.0)

    result = validate_cad_geometry(wrong_wp, cad_spec)
    assert result["valid"] is False
    assert result["fit_score"] == 0.0
    assert result["metrics"]["bbox_valid"] is False
    assert any("Bounding box dimension 'zlen'" in iss for iss in result["issues"])


